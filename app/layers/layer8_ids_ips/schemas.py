
from datetime import datetime, timezone
from enum import Enum
from ipaddress import ip_address

from pydantic import BaseModel, ConfigDict, Field, field_validator


class EventType(str, Enum):
    NETWORK_CONNECTION = "network_connection"
    AUTHENTICATION_FAILURE = "authentication_failure"
    PORT_SCAN = "port_scan"
    SUSPICIOUS_PAYLOAD = "suspicious_payload"
    RATE_ANOMALY = "rate_anomaly"
    POLICY_VIOLATION = "policy_violation"


class ThreatSeverity(str, Enum):
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


class DetectionAction(str, Enum):
    ALERT = "alert"
    BLOCK = "block"
    MONITOR = "monitor"


class ThreatStatus(str, Enum):
    DETECTED = "detected"
    CONFIRMED = "confirmed"
    FALSE_POSITIVE = "false_positive"
    RESOLVED = "resolved"


class SecurityEvent(BaseModel):
    """Normalized event submitted to the IDS detection engine."""

    model_config = ConfigDict(extra="forbid")

    event_id: str = Field(min_length=1, max_length=128)
    event_type: EventType
    timestamp: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc)
    )

    source_ip: str | None = None
    destination_ip: str | None = None
    source_port: int | None = Field(default=None, ge=1, le=65535)
    destination_port: int | None = Field(default=None, ge=1, le=65535)

    protocol: str = Field(default="UNKNOWN", max_length=16)
    username: str | None = Field(default=None, max_length=128)
    description: str = Field(default="", max_length=1000)

    # This is event metadata, not a trusted security verdict.
    attributes: dict[str, str | int | float | bool | None] = Field(
        default_factory=dict
    )

    @field_validator("event_id")
    @classmethod
    def validate_event_id(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("event_id cannot be blank")
        return value

    @field_validator("source_ip", "destination_ip")
    @classmethod
    def validate_ip_address(cls, value: str | None) -> str | None:
        if value is None:
            return None

        try:
            return str(ip_address(value))
        except ValueError as exc:
            raise ValueError("Invalid IP address") from exc

    @field_validator("protocol")
    @classmethod
    def normalize_protocol(cls, value: str) -> str:
        value = value.strip().upper()
        if not value:
            raise ValueError("Protocol cannot be blank")
        return value

    @field_validator("username")
    @classmethod
    def normalize_username(cls, value: str | None) -> str | None:
        if value is None:
            return None

        value = value.strip()
        if not value:
            raise ValueError("Username cannot be blank")
        return value


class DetectionRule(BaseModel):
    """A configurable rule used to identify suspicious events."""

    model_config = ConfigDict(extra="forbid")

    rule_id: str = Field(min_length=1, max_length=64)
    name: str = Field(min_length=1, max_length=128)
    description: str = Field(default="", max_length=500)

    event_types: list[EventType] = Field(min_length=1, max_length=20)
    severity: ThreatSeverity = ThreatSeverity.MEDIUM
    action: DetectionAction = DetectionAction.ALERT

    enabled: bool = True
    priority: int = Field(default=100, ge=1, le=65535)

    # Exact attribute conditions, not arbitrary executable expressions.
    attribute_equals: dict[str, str | int | float | bool] = Field(
        default_factory=dict
    )

    @field_validator("rule_id", "name")
    @classmethod
    def validate_nonblank_text(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("Value cannot be blank")
        return value

    @field_validator("event_types")
    @classmethod
    def validate_event_types(
        cls, values: list[EventType]
    ) -> list[EventType]:
        if not values:
            raise ValueError("At least one event type is required")

        if len(values) != len(set(values)):
            raise ValueError("Duplicate event types are not allowed")

        return values


class ThreatAlert(BaseModel):
    """A detection result generated by the IDS engine."""

    model_config = ConfigDict(extra="forbid")

    alert_id: str = Field(min_length=1, max_length=128)
    event_id: str = Field(min_length=1, max_length=128)
    rule_id: str = Field(min_length=1, max_length=64)

    severity: ThreatSeverity
    action: DetectionAction
    status: ThreatStatus = ThreatStatus.DETECTED

    message: str = Field(min_length=1, max_length=1000)
    detected_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc)
    )


class ResponseRequest(BaseModel):
    """Requests a response to a detected security event."""

    model_config = ConfigDict(extra="forbid")

    alert_id: str = Field(min_length=1, max_length=128)
    action: DetectionAction
    reason: str = Field(min_length=1, max_length=500)

    source_ip: str | None = None
    destination_ip: str | None = None

    @field_validator("alert_id", "reason")
    @classmethod
    def validate_nonblank_text(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("Value cannot be blank")
        return value

    @field_validator("source_ip", "destination_ip")
    @classmethod
    def validate_response_ip(cls, value: str | None) -> str | None:
        if value is None:
            return None

        try:
            return str(ip_address(value))
        except ValueError as exc:
            raise ValueError("Invalid IP address") from exc


class ResponseDecision(BaseModel):
    """Describes the response decision; does not enforce network blocks."""

    model_config = ConfigDict(extra="forbid")

    alert_id: str = Field(min_length=1, max_length=128)
    action: DetectionAction
    executed: bool = False
    message: str = Field(min_length=1, max_length=500)
